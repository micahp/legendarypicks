#!/usr/bin/env python3
"""Source-to-consumer manifest for the NFL sequence generator. Read-only.

For every Python module under scripts/nfl_sequence it records the git blob hash, the last commit that touched it, its
line count, its docstring summary, the modules that import it (consumers), the modules it imports from this directory,
and the data paths or tables it names. Writes JSON and a Markdown table. Reads only the git index and file contents of
the current checkout.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], cwd=HERE, text=True).strip()
DIR = os.path.relpath(HERE, REPO)
DATA_RE = re.compile(r"""['"]([^'"]*(?:docs/|data/|\.json|\.csv|evidence|nfl_pbp)[^'"]*)['"]""")


def git(*args):
    return subprocess.check_output(['git', *args], cwd=REPO, text=True).strip()


def modules():
    names = [n for n in os.listdir(HERE) if n.endswith('.py') and not n.startswith('__')]
    return sorted(names)


def summary(text):
    m = re.search(r'"""(.+?)(?:\n\n|""")', text, re.S)
    if not m:
        return ''
    return ' '.join(m.group(1).split())[:200]


def build():
    names = modules()
    texts = {n: open(os.path.join(HERE, n), encoding='utf-8', errors='replace').read() for n in names}
    stems = {n[:-3]: n for n in names}
    consumers = {n: [] for n in names}
    imports = {n: [] for n in names}
    for n, t in texts.items():
        for stem, target in stems.items():
            if target == n:
                continue
            if re.search(rf'^\s*(from|import)\s+{re.escape(stem)}\b', t, re.M):
                imports[n].append(stem)
                consumers[target].append(n)
    records = []
    for n in names:
        path = os.path.join(DIR, n)
        blob = git('hash-object', path)
        last = git('log', '-1', '--format=%h %ad', '--date=short', '--', path)
        text = texts[n]
        data = sorted({m for m in DATA_RE.findall(text)})[:40]
        records.append({
            'module': n,
            'blob': blob,
            'sha256': hashlib.sha256(text.encode('utf-8')).hexdigest(),
            'lines': text.count('\n') + 1,
            'last_commit': last,
            'summary': summary(text),
            'imports_from_this_dir': sorted(imports[n]),
            'consumers': sorted(consumers[n]),
            'data_references': data,
        })
    return records


def main():
    out_dir = os.path.join(REPO, 'docs', 'research')
    records = build()
    head = git('rev-parse', '--short', 'HEAD')
    payload = {'schema': 'lp.nfl-sequence.source-manifest.v1', 'checkout_head': head, 'modules': records}
    json_path = os.path.join(out_dir, 'LP-EVENT-INTEGRATION-SOURCE-MANIFEST-2026-10-28.json')
    md_path = os.path.join(out_dir, 'LP-EVENT-INTEGRATION-SOURCE-MANIFEST-2026-10-28.md')
    os.makedirs(out_dir, exist_ok=True)
    with open(json_path, 'w') as f:
        json.dump(payload, f, indent=1, sort_keys=True)
    lines = [
        '# NFL sequence generator: source manifest', '',
        f'Generated by `scripts/nfl_sequence/build_source_manifest.py` at checkout `{head}`. Modules: {len(records)}.', '',
        '| module | lines | last commit | consumers | imports from here | summary |',
        '|---|---:|---|---|---|---|',
    ]
    for r in records:
        lines.append('| `{}` | {} | {} | {} | {} | {} |'.format(
            r['module'], r['lines'], r['last_commit'], ', '.join(r['consumers']) or '-',
            ', '.join(r['imports_from_this_dir']) or '-', r['summary'].replace('|', '/')))
    with open(md_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {len(records)} modules to {md_path}')


if __name__ == '__main__':
    main()
