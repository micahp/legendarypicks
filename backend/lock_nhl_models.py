#!/usr/bin/env python3
"""Lock all NHL model outputs in the per-game T-90 minute window.

The feed is generated by the research model. Every model output is stored as its
own immutable row. This command defaults to dry-run and refuses either LP DB.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import sys

from nhl_model_store import (DEFAULT_DB, DEFAULT_FEED, NHLModelError, ensure_schema,
                             lock_feed, open_db, parse_time, read_feed)


def _assert_standalone(path: str) -> None:
    if os.path.basename(os.path.realpath(path)) in {"picks.db", "picks.dev.db"}:
        raise SystemExit("refusing Legendary Picks database path: %s" % path)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--feed", default=DEFAULT_FEED)
    parser.add_argument("--db", default=os.environ.get("NHL_MODEL_DB_PATH", DEFAULT_DB))
    parser.add_argument("--now", help="timezone-qualified ISO time, for deterministic checks")
    parser.add_argument("--apply", action="store_true", help="write immutable lock rows")
    args = parser.parse_args(argv)
    _assert_standalone(args.db)
    now = parse_time(args.now) if args.now else dt.datetime.now(dt.timezone.utc)
    try:
        feed = read_feed(args.feed)
        # A dry run uses only an in-memory database and cannot create or modify a data file.
        con = open_db(args.db if args.apply else ":memory:")
        try:
            ensure_schema(con)
            report = lock_feed(con, feed, now)
        finally:
            con.close()
    except NHLModelError as exc:
        print("NHL lock failed: %s" % exc, file=sys.stderr)
        return 1
    mode = "applied" if args.apply else "dry-run"
    print("{mode} at {time}: {feed_games} feed games, {due_games} due, {locked_rows} model locks, "
          "{already_locked} already locked, {outside_window} outside window, "
          "{missed_model_rows} model locks missed T-90 and recorded".format(
              mode=mode, time=now.isoformat(), **report))
    if report["missed_window"]:
        print("warning: a forecast outside its one-minute T-90 lock window was not backfilled", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
