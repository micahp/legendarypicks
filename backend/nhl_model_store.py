def read_feed(path: str = DEFAULT_FEED) -> dict:
    try:
        if path.endswith(".jsonl"):
            payload = _feed_from_jsonl(path)
        else:
            with open(path, "r", encoding="utf-8") as handle:
                payload = json.load(handle)
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        raise NHLModelError("cannot read forecast feed %s: %s" % (path, exc)) from exc
    if not isinstance(payload, dict) or not payload.get("model_version"):
        raise NHLModelError("forecast feed is missing model_version")
    if not isinstance(payload.get("games"), list):
        raise NHLModelError("forecast feed games must be a list")
    return payload


def _read_jsonl_locked(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_SH)
        rows = [json.loads(line) for line in handle if line.strip()]
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
    return rows


def _feed_from_jsonl(path: str) -> dict:
    # The research writer appends the complete three-model set while holding this ledger lock.
    records = _read_jsonl_locked(path)
    if not records:
        raise NHLModelError("forecast ledger is empty")
    distribution_path = os.path.join(os.path.dirname(path), "score_distributions.jsonl")
    distributions = _read_jsonl_locked(distribution_path)
    distributions_by_id = {}
    for distribution in distributions:
        forecast_id = str(distribution.get("forecast_id") or "")
        if not forecast_id or forecast_id in distributions_by_id:
            raise NHLModelError("score-distribution ledger has a missing or duplicate forecast id")
        distributions_by_id[forecast_id] = distribution
    grouped: dict[str, dict] = {}
    for row in records:
        gid = str(row.get("game_id") or "")
        model_key = str(row.get("model_name") or "")
        version = str(row.get("model_version") or "")
        if not gid or model_key not in MODEL_KEYS or not version:
            raise NHLModelError("forecast ledger row has no game/model identity")
        game = grouped.get(gid)
        identity = (version, row.get("game_date"), row.get("scheduled_start_utc"),
                    row.get("home_team"), row.get("away_team"), row.get("forecasted_at_utc"),
                    row.get("feature_snapshot"))
        if game is None:
            game = {"game_id": int(gid), "game_date": row["game_date"],
                    "scheduled_start_utc": row["scheduled_start_utc"],
                    "home_team": row["home_team"], "away_team": row["away_team"],
                    "forecasted_at_utc": row["forecasted_at_utc"],
                    "feature_snapshot": row["feature_snapshot"],
                    "models": {}, "_identity": identity}
            grouped[gid] = game
        elif game["_identity"] != identity:
            raise NHLModelError("forecast ledger rows disagree on game identity/features for %s" % gid)
        if model_key in game["models"]:
            raise NHLModelError("forecast ledger duplicates %s/%s" % (gid, model_key))
        forecast = dict(row)
        if "joint_score_probability_matrix_home_rows_away_columns" not in forecast:
            distribution = distributions_by_id.get(str(row.get("forecast_id") or ""))
            if distribution is None:
                raise NHLModelError("forecast ledger lacks score distribution for %s/%s" % (gid, model_key))
            identity = (str(distribution.get("game_id")), distribution.get("model_name"),
                        distribution.get("model_version"), distribution.get("forecasted_at_utc"))
            expected_identity = (gid, model_key, version, row.get("forecasted_at_utc"))
            if identity != expected_identity:
                raise NHLModelError("score distribution identity disagrees for %s/%s" % (gid, model_key))
            forecast_bytes = (json.dumps(row, sort_keys=True, separators=(",", ":"),
                                         ensure_ascii=False) + "\n").encode("utf-8")
            expected_hash = hashlib.sha256(forecast_bytes).hexdigest()
            if distribution.get("forecast_record_sha256") != expected_hash:
                raise NHLModelError("score distribution does not match immutable forecast %s/%s" % (gid, model_key))
            score_distribution = distribution.get("score_probability_distribution")
            if not isinstance(score_distribution, dict):
                raise NHLModelError("score distribution is malformed for %s/%s" % (gid, model_key))
            forecast.update(score_distribution)
            forecast["score_distribution_source"] = {
                "ledger": os.path.basename(distribution_path),
                "forecast_record_sha256": expected_hash,
                "derived_at_utc": distribution.get("derived_at_utc"),
                "model_artifact_sha256": distribution.get("model_artifact_sha256"),
                "derivation": distribution.get("derivation"),
            }
        game["models"][model_key] = forecast
    games = []
    versions = set()
    for gid, game in sorted(grouped.items(), key=lambda item: (item[1]["scheduled_start_utc"], item[0])):
        if set(game["models"]) != MODEL_KEYS:
            raise NHLModelError("forecast ledger has a partial model set for game %s" % gid)
        versions.add(game["_identity"][0])
        del game["_identity"]
        games.append(game)
    if len(versions) != 1:
        raise NHLModelError("forecast ledger mixes model versions")
    model_version = versions.pop()

    market_path = os.path.join(os.path.dirname(path), "market_quotes.jsonl")
    market_records = _read_jsonl_locked(market_path)
    latest_by_game_batch: dict[str, tuple[str, list[dict]]] = {}
    candidates: dict[str, dict[str, list[dict]]] = {}
    for row in market_records:
        gid = str(row.get("game_id") or "")
        batch = str(row.get("capture_batch_id") or row.get("captured_at_utc") or "")
        if gid and batch:
            candidates.setdefault(gid, {}).setdefault(batch, []).append(row)
    for gid, batches in candidates.items():
        chosen = max(batches.items(), key=lambda item: max(
            str(r.get("captured_at_utc") or "") for r in item[1]))
        latest_by_game_batch[gid] = chosen
    for game in games:
        capture = latest_by_game_batch.get(str(game["game_id"]))
        if not capture:
            game["markets"] = {"source": "Kalshi", "usable": False, "sides": []}
            continue
        batch, rows = capture
        sides = [{"team": row.get("market_side_team"),
                  "captured_at_utc": row.get("captured_at_utc"),
                  "spread": row.get("spread"), "quote_quality": row.get("quote_quality") or row.get("coverage_status"),
                  "yes_bid": row.get("yes_bid"), "yes_ask": row.get("yes_ask"),
                  "yes_bid_size": row.get("yes_bid_size"), "yes_ask_size": row.get("yes_ask_size"),
                  "last_trade_price": row.get("last_trade_price"), "volume": row.get("volume"),
                  "open_interest": row.get("open_interest"), "ticker": row.get("market_ticker")}
                 for row in rows]
        game["markets"] = {"source": "Kalshi", "capture_batch_id": batch,
                            "usable": len(sides) == 2 and all(
                                side["quote_quality"] == "two_sided_spread_at_most_20c" for side in sides),
                            "sides": sides}
    frozen_at = None
    model_path = os.path.join(os.path.dirname(path), "frozen_models_2026-27_v1.json")
    if os.path.exists(model_path):
        with open(model_path, "r", encoding="utf-8") as handle:
            frozen_at = json.load(handle).get("frozen_at_utc")
    return {"model_version": model_version, "frozen_at_utc": frozen_at,
            "source": "NHL prospective forecast ledger", "games": games}


def _finite_number(container: dict, key: str, context: str) -> float:
    value = container.get(key)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise NHLModelError("%s has invalid %s=%r" % (context, key, value))
    return float(value)


def validate_game(game: dict, model_version: str) -> tuple[dt.datetime, dt.datetime, dict[str, dict]]:
    gid = str(game.get("game_id") or "")
    context = "game %s" % (gid or "<missing id>")
    if not gid.isdigit() or len(gid) != 10:
        raise NHLModelError("%s has invalid NHL game id" % context)
    if not game.get("home_team") or not game.get("away_team") or game["home_team"] == game["away_team"]:
        raise NHLModelError("%s has invalid home/away team identity" % context)
    start = parse_time(game.get("scheduled_start_utc"))
    forecasted = parse_time(game.get("forecasted_at_utc"))
    features = game.get("feature_snapshot")
    if not isinstance(features, dict):
        raise NHLModelError("%s has no feature snapshot" % context)
    feature_as_of = parse_time(features.get("as_of_utc"))
    if forecasted > start or feature_as_of > forecasted:
        raise NHLModelError("%s uses forecast/features from after the scheduled game or forecast" % context)
    models = game.get("models")
    if not isinstance(models, dict) or not models:
        raise NHLModelError("%s has no per-model forecasts" % context)
    unknown = set(models) - MODEL_KEYS
    missing = MODEL_KEYS - set(models)
    if unknown or missing:
        raise NHLModelError("%s model set mismatch (missing=%s unknown=%s)" %
                            (context, sorted(missing), sorted(unknown)))
    prepared = {}
    for model_key, forecast in models.items():
        if not isinstance(forecast, dict) or not forecast.get("forecast_id"):
            raise NHLModelError("%s/%s missing forecast id" % (context, model_key))
        for key in ("home_expected_goals", "away_expected_goals", "projected_total_goals",
                    "projected_goal_differential_home", "home_win_probability", "p_over_5.5", "p_over_6.5"):
            _finite_number(forecast, key, "%s/%s" % (context, model_key))
        if not 0 <= float(forecast["home_win_probability"]) <= 1:
            raise NHLModelError("%s/%s home win probability outside [0,1]" % (context, model_key))
        if not 0 <= float(forecast["p_over_5.5"]) <= 1 or not 0 <= float(forecast["p_over_6.5"]) <= 1:
            raise NHLModelError("%s/%s total probability outside [0,1]" % (context, model_key))
        prepared[model_key] = forecast
    return start, feature_as_of, prepared


def lock_feed(con: sqlite3.Connection, payload: dict, now: dt.datetime) -> dict:
    """Lock every per-model forecast immediately (no T-90 window).

    The model output is immutable from the moment it is generated, so locking
    on projection is safe and ensures every projected game can be graded.
    """
    now = now.astimezone(UTC)
    report = {"feed_games": len(payload["games"]), "due_games": 0, "locked_rows": 0,
              "already_locked": 0, "outside_window": 0, "not_due": 0, "missed_window": 0,
              "missed_model_rows": 0, "pick_rows": 0, "already_picked": 0, "missing_picks": 0}
    seen_games = set()
    con.execute("BEGIN IMMEDIATE")
    try:
        for game in payload["games"]:
            start, features_as_of, models = validate_game(game, payload["model_version"])
            gid = str(game["game_id"])
            if gid in seen_games:
                raise NHLModelError("forecast feed duplicates game %s" % gid)
            seen_games.add(gid)
            until_start = start - now
            if until_start <= dt.timedelta(0):
                report["outside_window"] += 1
                # A game that reached its start with no lock row missed the window outright.
                # Recorded once per model; the table's primary key makes the retry a no-op.
                if not con.execute("SELECT 1 FROM nhl_game_projections WHERE game_id=? AND model_version=? LIMIT 1",
                                   (gid, payload["model_version"])).fetchone():
                    before = con.total_changes
                    for model_key in sorted(models):
                        con.execute("""INSERT OR IGNORE INTO nhl_projection_lock_events
                            (game_id,home_team,away_team,model_key,model_version,event_type,
                             observed_at_utc,scheduled_start_utc,feed_game_sha256)
                            VALUES (?,?,?,?,?,'missed_t90_window',?,?,?)""",
                                    (gid, str(game["home_team"]), str(game["away_team"]), model_key,
                                     payload["model_version"], iso_utc(now), iso_utc(start),
                                     sha256_json(game)))
                    added = con.total_changes - before
                    if added:
                        report["missed_window"] += 1
                        report["missed_model_rows"] += added
                continue
            if until_start > LOCK_LEAD:
                # Before T-90 this is a projection, not a lock. The preview path owns it and
                # the odds on it may still move.
                report["not_due"] += 1
                continue
            report["due_games"] += 1
            if parse_time(game["forecasted_at_utc"]) > now or features_as_of > now:
                raise NHLModelError("%s forecast/features were created after the lock timestamp" % gid)
            market_snapshot = dict(game.get("markets") or {})
            quote_times = [parse_time(side["captured_at_utc"])
                           for side in market_snapshot.get("sides", [])
                           if side.get("captured_at_utc")]
            market_snapshot["comparison_usable_at_lock"] = bool(
                market_snapshot.get("usable") and len(quote_times) >= 2 and
                all(dt.timedelta(0) <= now - captured <= dt.timedelta(minutes=15)
                    for captured in quote_times))
            market_snapshot["comparison_cutoff_utc"] = iso_utc(now)
            if not market_snapshot["comparison_usable_at_lock"]:
                market_snapshot["comparison_unavailable_reason"] = "no usable quote within 15 minutes before lock"
            source_meta = {"feed_source": payload.get("source"),
                           "feed_model_version": payload["model_version"],
                           "feed_frozen_at_utc": payload.get("frozen_at_utc"),
                           "game_source": {k: game.get(k) for k in
                                           ("game_id", "game_date", "scheduled_start_utc")},
                           "feature_snapshot_sha256": sha256_json(game["feature_snapshot"]),
                           "feed_game_sha256": sha256_json(game)}
            # Freeze the market quote in force at this instant with the pick. Only the puck
            # line determines the Vegas favorite; prices and freshness do not gate selection.
            line = latest_line_at(con, gid, now)
            for model_key, forecast in models.items():
                # Which lock protocol produced this row. A T-90 payload carries its own; a
                # legacy feed has none and keeps the protocol those rows were actually made
                # under. Not part of snapshot_sha256, so existing locks stay idempotent.
                protocol = str(game.get("_protocol_version") or LEGACY_PROTOCOL_VERSION)
                record = {
                    "game_id": gid,
                    "season": int(gid[:4]),
                    "game_date": str(game.get("game_date") or "")[:10],
                    "scheduled_start_utc": iso_utc(start),
                    "home_team": str(game["home_team"]),
                    "away_team": str(game["away_team"]),
                    "model_key": model_key,
                    "model_version": str(payload["model_version"]),
                    "forecast_id": str(forecast["forecast_id"]),
                    "forecasted_at_utc": iso_utc(parse_time(game["forecasted_at_utc"])),
                    "features_as_of_utc": iso_utc(features_as_of),
                    "locked_at_utc": iso_utc(now),
                    "home_expected_goals": float(forecast["home_expected_goals"]),
                    "away_expected_goals": float(forecast["away_expected_goals"]),
                    "projected_total_goals": float(forecast["projected_total_goals"]),
                    "projected_goal_differential_home": float(forecast["projected_goal_differential_home"]),
                    "home_win_probability": float(forecast["home_win_probability"]),
                    "p_over_5_5": float(forecast["p_over_5.5"]),
                    "p_over_6_5": float(forecast["p_over_6.5"]),
                    "forecast_output_json": canonical_json(forecast),
                    "feature_snapshot_json": canonical_json(game["feature_snapshot"]),
                    "market_snapshot_json": canonical_json(market_snapshot),
                    "source_metadata_json": canonical_json(source_meta),
                    "protocol_version": protocol,
                }
                record["snapshot_sha256"] = sha256_json({
                    key: record[key] for key in (
                        "game_id", "season", "game_date", "scheduled_start_utc", "home_team", "away_team",
                        "model_key", "model_version", "forecast_id", "forecasted_at_utc",
                        "features_as_of_utc", "home_expected_goals", "away_expected_goals",
                        "projected_total_goals", "projected_goal_differential_home", "home_win_probability",
                        "p_over_5_5", "p_over_6_5", "forecast_output_json", "feature_snapshot_json")
                })
                prior = con.execute(
                    "SELECT snapshot_sha256 FROM nhl_game_projections WHERE game_id=? AND model_key=? AND model_version=?",
                    (gid, model_key, payload["model_version"])).fetchone()
                if prior:
                    if prior[0] != record["snapshot_sha256"]:
                        raise NHLModelError("%s/%s already locked with a different immutable snapshot" %
                                            (gid, model_key))
                    report["already_locked"] += 1
                    continue
                cols = ",".join(record)
                marks = ",".join("?" for _ in record)
                con.execute("INSERT INTO nhl_game_projections (%s) VALUES (%s)" % (cols, marks),
                            tuple(record.values()))
                report["locked_rows"] += 1
                # Freeze the pick only for the row locked in this run, against the line in
                # force now. Existing locks are immutable; missing historical picks stay missing.
                freeze_pick(con, game, model_key, payload["model_version"], forecast, line, now,
                            "lock", report, protocol)
        con.commit()
    except Exception:
        con.rollback()
        raise
    return report


def preview_feed(con: sqlite3.Connection, payload: dict, now: dt.datetime) -> dict:
    """Refresh unlocked previews without removing one before its lock row is committed."""
    now = now.astimezone(UTC)
    report = {"feed_games": len(payload["games"]), "preview_rows": 0,
              "already_locked": 0, "not_previewable": 0}
    con.execute("BEGIN IMMEDIATE")
    try:
        for game in payload["games"]:
            start, _features_as_of, models = validate_game(game, payload["model_version"])
            gid = str(game["game_id"])
            previewable = start - now > LOCK_LEAD
            if not previewable:
                report["not_previewable"] += 1
            for model_key, forecast in models.items():
                locked = con.execute(
                    "SELECT 1 FROM nhl_game_projections WHERE game_id=? AND model_key=? AND model_version=?",
                    (gid, model_key, payload["model_version"])).fetchone()
                if locked:
                    con.execute("DELETE FROM nhl_game_previews WHERE game_id=? AND model_key=? AND model_version=?",
                                (gid, model_key, payload["model_version"]))
                    report["already_locked"] += 1
                    continue
                if not previewable:
                    continue
                con.execute("""INSERT INTO nhl_game_previews
                    (game_id,season,game_date,scheduled_start_utc,home_team,away_team,model_key,model_version,
                     forecast_id,forecasted_at_utc,previewed_at_utc,home_expected_goals,away_expected_goals,
                     projected_total_goals,home_win_probability,p_over_5_5,p_over_6_5,forecast_output_json)
                    VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                    ON CONFLICT(game_id,model_key,model_version) DO UPDATE SET
                      season=excluded.season, game_date=excluded.game_date,
                      scheduled_start_utc=excluded.scheduled_start_utc,
                      home_team=excluded.home_team, away_team=excluded.away_team,
                      forecast_id=excluded.forecast_id, forecasted_at_utc=excluded.forecasted_at_utc,
                      previewed_at_utc=excluded.previewed_at_utc,
                      home_expected_goals=excluded.home_expected_goals,
                      away_expected_goals=excluded.away_expected_goals,
                      projected_total_goals=excluded.projected_total_goals,
                      home_win_probability=excluded.home_win_probability,
                      p_over_5_5=excluded.p_over_5_5, p_over_6_5=excluded.p_over_6_5,
                      forecast_output_json=excluded.forecast_output_json""",
                    (gid, int(gid[:4]), str(game.get("game_date") or "")[:10], iso_utc(start),
                     str(game["home_team"]), str(game["away_team"]), model_key, str(payload["model_version"]),
                     str(forecast["forecast_id"]), iso_utc(parse_time(game["forecasted_at_utc"])), iso_utc(now),
                     float(forecast["home_expected_goals"]), float(forecast["away_expected_goals"]),
                     float(forecast["projected_total_goals"]), float(forecast["home_win_probability"]),
                     float(forecast["p_over_5.5"]), float(forecast["p_over_6.5"]), canonical_json(forecast)))
                report["preview_rows"] += 1
        con.commit()
    except Exception:
        con.rollback()
        raise
    return report


def normalize_official_result(game_id: str, document: dict) -> dict | None:
    """Return official winner and non-shootout scoring target from an NHL landing payload."""
    if str(document.get("id") or "") != str(game_id):
        raise NHLModelError("gamecenter response id disagrees for %s" % game_id)
    if str(document.get("gameState") or "") not in FINAL_STATES:
        return None
    home = document.get("homeTeam") or {}
    away = document.get("awayTeam") or {}
    if not home.get("abbrev") or not away.get("abbrev"):
        raise NHLModelError("%s final response lacks team codes" % game_id)
    official_home = _score(home.get("score"), game_id, "official home")
    official_away = _score(away.get("score"), game_id, "official away")
    if official_home == official_away:
        raise NHLModelError("%s is final with tied official score" % game_id)

    scoring = (document.get("summary") or {}).get("scoring")
    if not isinstance(scoring, list):
        raise NHLModelError("%s final response lacks published scoring summary" % game_id)
    team_codes = {str(home["abbrev"]), str(away["abbrev"])}
    statistical = {str(home["abbrev"]): 0, str(away["abbrev"]): 0}
    for period in scoring:
        descriptor = period.get("periodDescriptor") or {}
        period_type = str(descriptor.get("periodType") or "")
        if period_type == "SO":
            continue
        if period_type not in COUNTED_PERIOD_TYPES:
            raise NHLModelError("%s has unsupported scoring period type %r" % (game_id, period_type))
        for goal in period.get("goals") or []:
            code = str(((goal.get("teamAbbrev") or {}).get("default")) or "")
            if code not in team_codes:
                raise NHLModelError("%s scoring goal has unknown team %r" % (game_id, code))
            statistical[code] += 1

    stat_home = statistical[str(home["abbrev"])]
    stat_away = statistical[str(away["abbrev"])]
    extra_home, extra_away = official_home - stat_home, official_away - stat_away
    if extra_home < 0 or extra_away < 0 or (extra_home, extra_away) not in ((0, 0), (1, 0), (0, 1)):
        raise NHLModelError("%s summary scoring does not reconcile to official score (%s-%s vs %s-%s)" %
                            (game_id, official_home, official_away, stat_home, stat_away))
    shootout = int(bool(extra_home or extra_away))
    if shootout and ((official_home > official_away) != bool(extra_home)):
        raise NHLModelError("%s shootout goal does not belong to official winner" % game_id)
    winner = "home" if official_home > official_away else "away"
    return {"official_home_goals": official_home, "official_away_goals": official_away,
            "statistical_home_goals": stat_home, "statistical_away_goals": stat_away,
            "official_winner": winner, "shootout_decided": shootout,
            "home_team": str(home["abbrev"]), "away_team": str(away["abbrev"])}


def _score(value: Any, game_id: str, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or int(value) != value:
        raise NHLModelError("%s has invalid %s score %r" % (game_id, label, value))
    return int(value)


def grade_result(con: sqlite3.Connection, game_id: str, result: dict, now: dt.datetime,
                 source_sha256: str, source_url: str) -> int:
    rows = con.execute("""
        SELECT * FROM nhl_game_projections WHERE game_id=?
        AND NOT EXISTS (
          SELECT 1 FROM nhl_projection_grades g
          WHERE g.game_id=nhl_game_projections.game_id
            AND g.model_key=nhl_game_projections.model_key
            AND g.model_version=nhl_game_projections.model_version)
        ORDER BY model_key, model_version
    """, (str(game_id),)).fetchall()
    inserted = 0
    for row in rows:
        if row["home_team"] != result["home_team"] or row["away_team"] != result["away_team"]:
            raise NHLModelError("%s NHL result matchup disagrees with locked teams" % game_id)
        y_home = float(result["official_winner"] == "home")
        p_home = float(row["home_win_probability"])
        p_clipped = min(max(p_home, EPS), 1 - EPS)
        brier = (p_home - y_home) ** 2
        logloss = -(y_home * math.log(p_clipped) + (1 - y_home) * math.log(1 - p_clipped))
        con.execute("""INSERT INTO nhl_projection_grades (
          game_id,model_key,model_version,official_home_goals,official_away_goals,
          statistical_home_goals,statistical_away_goals,official_winner,shootout_decided,
          home_win_brier,home_win_logloss,home_goal_error,away_goal_error,graded_at_utc,
          result_source,result_source_sha256) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
          (row["game_id"], row["model_key"], row["model_version"],
           result["official_home_goals"], result["official_away_goals"],
           result["statistical_home_goals"], result["statistical_away_goals"],
           result["official_winner"], result["shootout_decided"], brier, logloss,
           result["statistical_home_goals"] - row["home_expected_goals"],
           result["statistical_away_goals"] - row["away_expected_goals"],
           iso_utc(now), source_url, source_sha256))
        inserted += 1
    return inserted


def export_pick(row: sqlite3.Row | None, grade: dict | None, quote: dict | None = None) -> dict | None:
    """Serialize the frozen selection and result without wager-only presentation fields."""
    if row is None:
        return None
    pick = {"market": row["market"], "side": row["side"], "line": row["line"],
            "model_probability": row["model_probability"],
            "push_probability": row["push_probability"],
            "line_captured_at_utc": row["line_captured_at_utc"],
            "settlement_basis": row["settlement_basis"], "rule_version": row["rule_version"],
            "protocol_version": row["protocol_version"],
            "provenance": row["provenance"], "selected_at_utc": row["selected_at_utc"],
            "quote": quote, "result": None}
    if grade:
        pick["result"] = grade_pick(pick, grade)
    return pick


def export_locked(con: sqlite3.Connection, season: int) -> dict:
    """Build the UI projection artifact from locked DB rows, never from unlocked forecasts."""
    rows = con.execute("""
      SELECT p.*, g.official_home_goals AS final_home, g.official_away_goals AS final_away,
        g.statistical_home_goals AS target_home, g.statistical_away_goals AS target_away,
        g.official_winner, g.shootout_decided, g.home_win_brier, g.home_win_logloss,
        g.home_goal_error, g.away_goal_error, g.graded_at_utc
      FROM nhl_game_projections p LEFT JOIN nhl_projection_grades g
        USING (game_id,model_key,model_version)
      WHERE p.season=? ORDER BY p.scheduled_start_utc,p.game_id,p.model_key,p.locked_at_utc
    """, (int(season),)).fetchall()
    picks: dict[tuple, sqlite3.Row] = {}
    if con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='nhl_model_picks'").fetchone():
        picks = {(row["game_id"], row["model_key"], row["model_version"]): row
                 for row in con.execute("SELECT * FROM nhl_model_picks WHERE season=?", (int(season),))}
    quotes: dict[tuple, dict] = {}
    if con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='nhl_frozen_quotes'").fetchone():
        quotes = {(row["game_id"], row["source"], row["captured_at_utc"]): json.loads(row["quote_json"])
                  for row in con.execute("SELECT * FROM nhl_frozen_quotes")}
    games: dict[str, dict] = {}
    versions: dict[str, str] = {}
    for row in rows:
        gid = row["game_id"]
        game = games.setdefault(gid, {
            "game_id": int(gid), "game_date": row["game_date"],
            "scheduled_start_utc": row["scheduled_start_utc"],
            "home_team": row["home_team"], "away_team": row["away_team"],
            "forecasted_at_utc": row["forecasted_at_utc"],
            "locked_at_utc": row["locked_at_utc"],
            "feature_snapshot": json.loads(row["feature_snapshot_json"]),
            "models": {}, "markets": json.loads(row["market_snapshot_json"]),
            "result": None,
        })
        if (game["home_team"], game["away_team"], game["scheduled_start_utc"]) != (
                row["home_team"], row["away_team"], row["scheduled_start_utc"]):
            raise NHLModelError("stored locks disagree on game identity for %s" % gid)
        versions[row["model_key"]] = row["model_version"]
        grade = None
        if row["graded_at_utc"]:
            grade = {"official_home_goals": row["final_home"], "official_away_goals": row["final_away"],
                     "statistical_home_goals": row["target_home"], "statistical_away_goals": row["target_away"],
                     "official_winner": row["official_winner"], "shootout_decided": bool(row["shootout_decided"]),
                     "home_win_brier": row["home_win_brier"], "home_win_logloss": row["home_win_logloss"],
                     "home_goal_error": row["home_goal_error"], "away_goal_error": row["away_goal_error"],
                     "graded_at_utc": row["graded_at_utc"]}
            game["result"] = grade
        pick_row = picks.get((gid, row["model_key"], row["model_version"]))
        frozen_forecast = json.loads(row["forecast_output_json"])
        frozen_quote = None
        if pick_row:
            frozen_quote = quotes.get((gid, pick_row["line_source"], pick_row["line_captured_at_utc"]))
        else:
            lock_time = row["locked_at_utc"]
            prior_quotes = [(captured, quote) for (quote_game, _source, captured), quote in quotes.items()
                            if quote_game == gid and captured <= lock_time]
            if prior_quotes:
                frozen_quote = max(prior_quotes, key=lambda item: item[0])[1]
        quote_fresh = bool(frozen_quote and
                           dt.timedelta(0) <= parse_time(row["locked_at_utc"]) -
                           parse_time(frozen_quote["captured_at_utc"]) <= T90_QUOTE_MAX_AGE)
        line_grades = (grade_game_lines(frozen_forecast, grade, gid, frozen_quote, quote_fresh)
                       if grade else None)
        game["models"][row["model_key"]] = {
            **frozen_forecast,
            "forecast_id": row["forecast_id"], "model_version": row["model_version"],
            "locked_at_utc": row["locked_at_utc"], "home_expected_goals": row["home_expected_goals"],
            "away_expected_goals": row["away_expected_goals"],
            "projected_total_goals": row["projected_total_goals"],
            "projected_goal_differential_home": row["projected_goal_differential_home"],
            "home_win_probability": row["home_win_probability"], "p_over_5.5": row["p_over_5_5"],
            "p_over_6.5": row["p_over_6_5"], "grade": grade,
            "line_grades": line_grades,
            "locked_quote": frozen_quote,
            "pick": export_pick(pick_row, grade, frozen_quote),
            "pick_status": "selected" if pick_row else "missing",
        }
    missed = [dict(row) for row in con.execute("""
      SELECT e.game_id,e.home_team,e.away_team,e.model_key,e.model_version,
        e.observed_at_utc,e.scheduled_start_utc
      FROM nhl_projection_lock_events e WHERE CAST(substr(e.game_id,1,4) AS INTEGER)=?
      ORDER BY e.scheduled_start_utc,e.game_id,e.model_key
    """, (int(season),)).fetchall()]
    return {"model_version": "per-model-locked", "model_versions": versions,
            "default_model": "B7_elo_xg_poisson", "frozen_at_utc": max(
                (g["locked_at_utc"] for g in games.values()), default=None),
            "source": "NHL model lock database", "games": list(games.values()),
            "missed_locks": missed}


def export_previews(con: sqlite3.Connection, season: int, now: dt.datetime,
                    lines: dict | None = None) -> list[dict]:
    """Return every saved unlocked forecast until its immutable lock row exists.

    A preview is display-only: its pick is derived here, never stored, and carries no
    result. `lines` is the market snapshot to price it against; omitted means read the
    latest Bovada snapshot from this database.
    """
    if not con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='nhl_game_previews'").fetchone():
        return []
    if lines is None:
        lines = latest_game_lines(con)
    rows = con.execute("""
      SELECT pv.* FROM nhl_game_previews pv
      WHERE pv.season=?
        AND NOT EXISTS (SELECT 1 FROM nhl_game_projections p
                        WHERE p.game_id=pv.game_id AND p.model_key=pv.model_key
                          AND p.model_version=pv.model_version)
      ORDER BY pv.scheduled_start_utc,pv.game_id,pv.model_key
    """, (int(season),)).fetchall()
    games: dict[str, dict] = {}
    for row in rows:
        game = games.setdefault(row["game_id"], {
            "game_id": int(row["game_id"]), "game_date": row["game_date"],
            "scheduled_start_utc": row["scheduled_start_utc"],
            "home_team": row["home_team"], "away_team": row["away_team"], "models": {},
        })
        forecast = {
            **json.loads(row["forecast_output_json"]),
            "forecast_id": row["forecast_id"], "model_version": row["model_version"],
            "forecasted_at_utc": row["forecasted_at_utc"], "previewed_at_utc": row["previewed_at_utc"],
            "home_expected_goals": row["home_expected_goals"], "away_expected_goals": row["away_expected_goals"],
            "projected_total_goals": row["projected_total_goals"],
            "home_win_probability": row["home_win_probability"],
            "p_over_5.5": row["p_over_5_5"], "p_over_6.5": row["p_over_6_5"],
            "preview": True,
        }
        quote = lines.get(str(row["game_id"]))
        try:
            pick = model_pick(row["home_team"], row["away_team"], forecast, quote, str(row["game_id"]))
        except NHLModelError:
            # An incomplete forecast cannot support a model pick.
            pick = None
        # Previews are display-only; they are never inserted into picks or grade history.
        forecast["pick"] = None if pick is None else {
            **pick, "result": None, "rule_version": RULE_VERSION, "provenance": "preview",
            "quote": quote}
        forecast["pick_status"] = "selected" if pick else "missing"
        game["models"][row["model_key"]] = forecast
    return list(games.values())


def line_at_capture(con: sqlite3.Connection, game_id: str, source: str, captured_at: str) -> dict | None:
    """The exact captured quote at one timestamp, or None. Never a neighbouring snapshot."""
    if not source or not captured_at:
        return None
    row = con.execute("SELECT * FROM nhl_game_lines WHERE game_id=? AND source=? AND captured_at_utc=?",
                      (str(game_id), str(source), str(captured_at))).fetchone()
    return None if row is None else {key: row[key] for key in row.keys() if key != "game_id"}


def backfill_picks(con: sqlite3.Connection, season: int) -> dict:
    """Freeze quotes for existing picks without reconstructing missing historical picks.

    A row that already has a pick is left exactly as frozen: it is history, and it may have
    been produced under an earlier rule. Only its quote is added, and only from the snapshot
    actually captured at the timestamp the row recorded. A missing pick remains missing; a
    later invocation cannot apply today's selection rule to an old forecast.
    """
    report = {"games": 0, "pick_rows": 0, "already_picked": 0, "missing_picks": 0,
              "quotes_frozen": 0, "quotes_missing": 0, "skipped": 0}
    rows = con.execute("""
      SELECT game_id,model_key,model_version
      FROM nhl_game_projections WHERE season=?
      ORDER BY scheduled_start_utc,game_id,model_key
    """, (int(season),)).fetchall()
    seen: set[str] = set()
    con.execute("BEGIN IMMEDIATE")
    try:
        for row in rows:
            gid = row["game_id"]
            if gid not in seen:
                seen.add(gid)
                report["games"] += 1
            existing = con.execute("SELECT line_source,line_captured_at_utc FROM nhl_model_picks "
                                   "WHERE game_id=? AND model_key=? AND model_version=?",
                                   (gid, row["model_key"], row["model_version"])).fetchone()
            if existing:
                report["already_picked"] += 1
                if not existing["line_captured_at_utc"]:
                    continue
                quote = line_at_capture(con, gid, existing["line_source"], existing["line_captured_at_utc"])
                if quote is None:
                    report["quotes_missing"] += 1
                    continue
                freeze_quote(con, gid, quote)
                report["quotes_frozen"] += 1
                continue
            report["missing_picks"] += 1
        con.commit()
    except Exception:
        con.rollback()
        raise
    return report


def latest_game_lines(con: sqlite3.Connection) -> dict:
    """Latest Bovada snapshot per game, keyed by game id string. Empty if the table is missing."""
    if not con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='nhl_game_lines'").fetchone():
        return {}
    rows = con.execute("""
      SELECT l.* FROM nhl_game_lines l
      JOIN (SELECT game_id, MAX(captured_at_utc) AS latest FROM nhl_game_lines
            WHERE source='bovada' GROUP BY game_id) m
        ON l.game_id=m.game_id AND l.captured_at_utc=m.latest
      WHERE l.source='bovada'
    """).fetchall()
    return {row["game_id"]: {key: row[key] for key in row.keys() if key != "game_id"} for row in rows}


def write_standings(con: sqlite3.Connection, standings: list, captured_at: str) -> int:
    """Append one standings snapshot per team from the NHL standings API. Commits."""
    rows = [(int(str(team["seasonId"])[:4]), str(team["teamAbbrev"]["default"]), captured_at, str(team["date"]),
             int(team["gamesPlayed"]), int(team["wins"]), int(team["losses"]), int(team["otLosses"]),
             int(team["points"])) for team in standings]
    con.executemany(
        "INSERT INTO nhl_team_standings (season, team, captured_at_utc, standings_date, games_played, wins, "
        "losses, overtime_losses, points) VALUES (?,?,?,?,?,?,?,?,?)", rows)
    con.commit()
    return len(rows)


def latest_standings(con: sqlite3.Connection, season: int) -> dict:
    """Newest standings row per team for one season, keyed by team code. Empty if the table is missing."""
    if not con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='nhl_team_standings'").fetchone():
        return {}
    rows = con.execute("""
      SELECT s.* FROM nhl_team_standings s
      JOIN (SELECT team, MAX(captured_at_utc) AS latest FROM nhl_team_standings
            WHERE season=? GROUP BY team) m
        ON s.team=m.team AND s.captured_at_utc=m.latest
      WHERE s.season=?
    """, (int(season), int(season))).fetchall()
    return {row["team"]: {"games_played": row["games_played"], "wins": row["wins"], "losses": row["losses"],
                          "overtime_losses": row["overtime_losses"], "points": row["points"],
                          "standings_date": row["standings_date"]} for row in rows}


