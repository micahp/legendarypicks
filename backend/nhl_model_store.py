"""Immutable, per-model NHL forecast locks and official-result grading.

This database is deliberately separate from the Legendary Picks production DB. The
forecast feed is generated by the NHL research model and contains one output per
model; this module locks each output once inside the T-90 minute window.
"""
from __future__ import annotations

import datetime as dt
import fcntl
import hashlib
import json
import math
import os
import sqlite3
from typing import Any

UTC = dt.timezone.utc
LOCK_LEAD = dt.timedelta(minutes=90)
LOCK_WINDOW = dt.timedelta(minutes=1)
FINAL_GRACE = dt.timedelta(hours=4)
FINAL_STATES = frozenset(("OFF", "FINAL"))
COUNTED_PERIOD_TYPES = frozenset(("REG", "OT"))
DEFAULT_DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "nhl-model.dev.sqlite3")
DEFAULT_FEED = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "research", "nhl", "prospective-2026-27", "forecasts.jsonl")
MODEL_KEYS = frozenset(("B3_elo", "B5_xg_poisson", "B7_elo_xg_poisson"))
EPS = 1e-15


class NHLModelError(RuntimeError):
    """Invalid, incomplete, or contradictory forecast/result data."""


def parse_time(value: str) -> dt.datetime:
    try:
        parsed = dt.datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (TypeError, ValueError) as exc:
        raise NHLModelError("invalid ISO timestamp %r" % (value,)) from exc
    if parsed.tzinfo is None:
        raise NHLModelError("timestamp must include a timezone: %r" % value)
    return parsed.astimezone(UTC)


def iso_utc(value: dt.datetime) -> str:
    if value.tzinfo is None:
        raise NHLModelError("datetime must include a timezone")
    return value.astimezone(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")


def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
                      allow_nan=False)


def sha256_json(value: Any) -> str:
    return hashlib.sha256(canonical_json(value).encode("utf-8")).hexdigest()


def open_db(path: str = DEFAULT_DB, readonly: bool = False) -> sqlite3.Connection:
    if readonly:
        uri = "file:%s?mode=ro" % os.path.abspath(path)
        con = sqlite3.connect(uri, timeout=30, uri=True)
    else:
        con = sqlite3.connect(path, timeout=30)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys=ON")
    return con


